package org.example;

/** Represents the type of academic assessment. */
public enum AssessmentType {
    /** Exam. */
    EXAM,
    /** Differentiated credit. */
    DIFF_CREDIT,
    /** Pass/fail credit (non-differentiated). */
    PASS_FAIL_CREDIT,
    /** Qualification work (thesis) defense. */
    QUALIFICATION_WORK
}
